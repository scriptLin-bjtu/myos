#!/bin/bash

# 创建用户程序目录
mkdir -p target/user_programs

# 生成一个简单的示例二进制文件，用于测试
# 这个文件包含一些简单的机器码，用于测试批处理系统
cat > target/user_programs/hello.bin << EOF
\x48\xc7\xc0\x01\x00\x00\x00\x48\xbf\x00\x10\x40\x00\x00\x00\x00\x00\x48\xc7\xc6\x0d\x00\x00\x00\xcd\x80\x48\xc7\xc0\x02\x00\x00\x00\x48\xc7\xc7\x00\x00\x00\x00\xcd\x80\x48\x65\x6c\x6c\x6f\x2c\x20\x57\x6f\x72\x6c\x64\x21
EOF

# 复制相同的文件作为fibonacci.bin
cp target/user_programs/hello.bin target/user_programs/fibonacci.bin

echo "用户程序编译完成！"
